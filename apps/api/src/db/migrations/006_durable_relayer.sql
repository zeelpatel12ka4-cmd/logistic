ALTER TABLE relayer_jobs
  ADD COLUMN IF NOT EXISTS next_run_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  ADD COLUMN IF NOT EXISTS max_attempts INTEGER NOT NULL DEFAULT 5,
  ADD COLUMN IF NOT EXISTS signer_address VARCHAR(42),
  ADD COLUMN IF NOT EXISTS signer_nonce BIGINT,
  ADD COLUMN IF NOT EXISTS locked_by VARCHAR(64),
  ADD COLUMN IF NOT EXISTS locked_at TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS confirmed_at TIMESTAMPTZ;

CREATE INDEX IF NOT EXISTS idx_relayer_jobs_poll
  ON relayer_jobs(status, next_run_at)
  WHERE status IN ('PENDING', 'RETRYING', 'PROCESSING', 'SUBMITTED');

CREATE TABLE IF NOT EXISTS relayer_signer_nonces (
  signer_address VARCHAR(42) PRIMARY KEY,
  next_nonce BIGINT NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
